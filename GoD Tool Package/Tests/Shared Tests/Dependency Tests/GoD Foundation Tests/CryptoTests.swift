    // MARK: - SHA-1 additional vectors

    func testSHA1EmptyString() {
        // SHA1("") = da39a3ee5e6b4b0d3255bfef95601890afd80709
        let result = SHA1.hash([UInt8]())
        let expected: [UInt8] = [0xda, 0x39, 0xa3, 0xee, 0x5e, 0x6b, 0x4b, 0x0d, 0x32, 0x55,
                                 0xbf, 0xef, 0x95, 0x60, 0x18, 0x90, 0xaf, 0xd8, 0x07, 0x09]
        XCTAssertEqual(result, expected)
    }

    func testSHA1LongerMessage() {
        // SHA1("abcdbcdecdefdefgefghfghighijhijkijkljklmklmnlmnomnopnopq")
        // = 84983e441c3bd26ebaae4aa1f95129e5e54670f1
        let message = "abcdbcdecdefdefgefghfghighijhijkijkljklmklmnlmnomnopnopq"
        let bytes = Array(message.utf8)
        let result = SHA1.hash(bytes)
        let expected: [UInt8] = [0x84, 0x98, 0x3e, 0x44, 0x1c, 0x3b, 0xd2, 0x6e, 0xba, 0xae,
                                 0x4a, 0xa1, 0xf9, 0x51, 0x29, 0xe5, 0xe5, 0x46, 0x70, 0xf1]
        XCTAssertEqual(result, expected)
    }

    func testSHA1GoDDataInterface() {
        let data = GoDData(byteStream: [0x61, 0x62, 0x63], byteOrder: .big)
        let result = SHA1.hash(data)
        XCTAssertEqual(result.length, 20)
        XCTAssertEqual(result.rawBytes[0], 0xa9)
    }

    // MARK: - AES with GoDData interface

    func testAES128CBCGoDDataInterface() {
        let key: [UInt8] = [0x2b, 0x7e, 0x15, 0x16, 0x28, 0xae, 0xd2, 0xa6, 0xab, 0xf7, 0x15, 0x88, 0x09, 0xcf, 0x4f, 0x3c]
        let iv: [UInt8] = [0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x0a, 0x0b, 0x0c, 0x0d, 0x0e, 0x0f]
        let plaintext = GoDData(byteStream: [UInt8](repeating: 0x42, count: 32), byteOrder: .big)

        let encrypted = AES128CBC.encrypt(data: plaintext, key: key, iv: iv)
        let decrypted = AES128CBC.decrypt(data: encrypted, key: key, iv: iv)

        XCTAssertEqual(decrypted.rawBytes, plaintext.rawBytes)
        XCTAssertEqual(decrypted.byteOrder, plaintext.byteOrder, "Byte order should be preserved")
    }

    // MARK: - AES with zero IV (used by Wii)

    func testAES128CBCZeroIV() {
        let key: [UInt8] = Array(repeating: 0x00, count: 16)
        let iv: [UInt8] = Array(repeating: 0x00, count: 16)
        let plaintext: [UInt8] = Array(repeating: 0x00, count: 16)

        let encrypted = AES128CBC.encrypt(bytes: plaintext, key: key, iv: iv)
        let decrypted = AES128CBC.decrypt(bytes: encrypted, key: key, iv: iv)
        XCTAssertEqual(decrypted, plaintext)
        XCTAssertNotEqual(encrypted, plaintext, "Encrypted data should differ from plaintext even with zero key/iv")
    }
