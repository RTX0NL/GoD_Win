import XCTest
@testable import GoDFoundation

final class CryptoTests: XCTestCase {
    func testSHA1KnownVector() {
        let result = SHA1.hash([0x61, 0x62, 0x63])
        let expected: [UInt8] = [0xa9, 0x99, 0x3e, 0x36, 0x47, 0x06, 0x81, 0x6a, 0xba, 0x3e,
                                 0x25, 0x71, 0x78, 0x50, 0xc2, 0x6c, 0x9c, 0xd0, 0xd8, 0x9d]
        XCTAssertEqual(result, expected, "SHA1('abc') should match known vector")
    }

    func testAES128CBCEncrypt() {
        let key: [UInt8] = [0x2b, 0x7e, 0x15, 0x16, 0x28, 0xae, 0xd2, 0xa6, 0xab, 0xf7, 0x15, 0x88, 0x09, 0xcf, 0x4f, 0x3c]
        let iv: [UInt8] = [0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x0a, 0x0b, 0x0c, 0x0d, 0x0e, 0x0f]
        let plaintext: [UInt8] = [0x6b, 0xc1, 0xbe, 0xe2, 0x2e, 0x40, 0x9f, 0x96, 0xe9, 0x3d, 0x7e, 0x11, 0x73, 0x93, 0x17, 0x2a]
        let expected: [UInt8] = [0x76, 0x49, 0xab, 0xac, 0x81, 0x19, 0xb2, 0x46, 0xce, 0xe9, 0x8e, 0x9b, 0x12, 0xe9, 0x19, 0x7d]

        let result = AES128CBC.encrypt(bytes: plaintext, key: key, iv: iv)
        XCTAssertEqual(result, expected, "AES-128-CBC encrypt should match NIST test vector")
    }

    func testAES128CBCDecrypt() {
        let key: [UInt8] = [0x2b, 0x7e, 0x15, 0x16, 0x28, 0xae, 0xd2, 0xa6, 0xab, 0xf7, 0x15, 0x88, 0x09, 0xcf, 0x4f, 0x3c]
        let iv: [UInt8] = [0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x0a, 0x0b, 0x0c, 0x0d, 0x0e, 0x0f]
        let ciphertext: [UInt8] = [0x76, 0x49, 0xab, 0xac, 0x81, 0x19, 0xb2, 0x46, 0xce, 0xe9, 0x8e, 0x9b, 0x12, 0xe9, 0x19, 0x7d]
        let expected: [UInt8] = [0x6b, 0xc1, 0xbe, 0xe2, 0x2e, 0x40, 0x9f, 0x96, 0xe9, 0x3d, 0x7e, 0x11, 0x73, 0x93, 0x17, 0x2a]

        let result = AES128CBC.decrypt(bytes: ciphertext, key: key, iv: iv)
        XCTAssertEqual(result, expected, "AES-128-CBC decrypt should match NIST test vector")
    }

    func testAES128CBCRoundTrip() {
        let key: [UInt8] = [0x2b, 0x7e, 0x15, 0x16, 0x28, 0xae, 0xd2, 0xa6, 0xab, 0xf7, 0x15, 0x88, 0x09, 0xcf, 0x4f, 0x3c]
        let iv: [UInt8] = [0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x0a, 0x0b, 0x0c, 0x0d, 0x0e, 0x0f]
        let plaintext: [UInt8] = Array(repeating: 0x42, count: 64)

        let encrypted = AES128CBC.encrypt(bytes: plaintext, key: key, iv: iv)
        let decrypted = AES128CBC.decrypt(bytes: encrypted, key: key, iv: iv)
        XCTAssertEqual(decrypted, plaintext, "Encrypt then decrypt should return original")
    }
}
