    func testSHA1KnownVector() {
        let result = SHA1.hash([0x61, 0x62, 0x63])
        let expected: [UInt8] = [0xa9, 0x99, 0x3e, 0x36, 0x47, 0x06, 0x81, 0x6a, 0xba, 0x3e,
                                 0x25, 0x71, 0x78, 0x50, 0xc2, 0x6c, 0x9c, 0xd0, 0xd8, 0x9d]
        XCTAssertEqual(result, expected, "SHA1('abc') should match known vector")
    }

